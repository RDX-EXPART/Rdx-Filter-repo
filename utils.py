def clean_display_name(file_name: str) -> str:
    if not file_name:
        return ""
    words = []
    for word in str(file_name).split():
        cleaned = word.strip("[]{}()")
        if not cleaned or cleaned.startswith("@") or cleaned.startswith("www."):
            continue
        words.append(cleaned)
    return " ".join(words)

def clean_index_name(file_name: str) -> str:
    if not file_name:
        return ""
    file_name = re.sub(r"[\[\]{}()_\-.+]+", " ", str(file_name))
    file_name = re.sub(r"\s+", " ", file_name).strip()
    return file_name

def clean_index_file_name(file_name: str) -> str:
    return clean_index_name(file_name)
