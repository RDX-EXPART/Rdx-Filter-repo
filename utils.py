async def get_verify_shorted_link(link):
    API = SHORTLINK_API
    URL = SHORTLINK_URL
    https = link.split(":")[0]
    if "http" == https:
        https = "https"
        link = link.replace("http", https)

    if URL == "api.shareus.in":
        url = f"https://{URL}/shortLink"
        params = {"token": API,
                  "format": "json",
                  "link": link,
                  }
        try:
            async with aiohttp.ClientSession() as session:
                async with session.get(url, params=params, raise_for_status=True, ssl=False) as response:
                    data = await response.json(content_type="text/html")
                    if data["status"] == "success":
                        return data["shortlink"]
                    else:
                        logger.error(f"Error: {data['message']}")
                        return f'https://{URL}/shortLink?token={API}&format=json&link={link}'

        except Exception as e:
            logger.error(e)
            return f'https://{URL}/shortLink?token={API}&format=json&link={link}'
    else:
        url = f'https://{URL}/api'
        params = {'api': API,
                  'url': link,
                  }
        try:
            async with aiohttp.ClientSession() as session:
                async with session.get(url, params=params, raise_for_status=True, ssl=False) as response:
                    data = await response.json()
                    if data["status"] == "success":
                        return data['shortenedUrl']
                    else:
                        logger.error(f"Error: {data['message']}")
                        return f'https://{URL}/api?api={API}&link={link}'

        except Exception as e:
            logger.error(e)
            return f'{URL}/api?api={API}&link={link}'

async def check_token(bot, userid, token, fileid):
    user = await bot.get_users(userid)
    if not await db.is_user_exist(user.id):
        await db.add_user(user.id, user.first_name)
        await bot.send_message(LOG_CHANNEL, script.LOG_TEXT_P.format(user.id, user.mention))

    database_result = await vr_db.consume_token(user.id, token, fileid)
    if database_result is not None:
        if database_result and user.id in TOKENS and token in TOKENS[user.id]:
            token_state = TOKENS[user.id][token]
            if isinstance(token_state, dict):
                token_state["used"] = True
            else:
                TOKENS[user.id][token] = True
        return database_result

    token_state = TOKENS.get(user.id, {}).get(token)
    if token_state is None:
        return False
    if isinstance(token_state, bool):
        return not token_state
    if token_state.get("used") or token_state.get("file_id") != str(fileid):
        return False
    if token_state.get("expires_at") <= datetime.utcnow():
        return False
    token_state["used"] = True
    return True

async def get_token(bot, userid, link, fileid):
    user = await bot.get_users(userid)
    if not await db.is_user_exist(user.id):
        await db.add_user(user.id, user.first_name)
        await bot.send_message(LOG_CHANNEL, script.LOG_TEXT_P.format(user.id, user.mention))
    token = secrets.token_hex(4)
    expires_at = datetime.utcnow() + timedelta(minutes=VERIFY_TOKEN_MINUTES)
    TOKENS[user.id] = {
        token: {
            "used": False,
            "file_id": str(fileid),
            "expires_at": expires_at,
        }
    }
    await vr_db.save_token(user.id, token, fileid, expires_at)
    target_url = f"{link}verify-{user.id}-{token}-{fileid}"
    protected_url = await create_protected_verification_url(
        target_url,
        user.id,
        VERIFY_TOKEN_MINUTES * 60,
    )
    if protected_url is not None:
        return protected_url

    # Preserve the existing shortener flow when Anti-Bypass is completely
    # disabled. When it is enabled, the protection service handles the
    # shortener callback and must not be shortened a second time.
    shortened_verify_url = await get_verify_shorted_link(target_url)
    return str(shortened_verify_url)

async def get_verify_status(userid):
    """Read the shared, user-level verification expiry from persistent storage.

    Do not trust a process-local cache here: PM and group requests can arrive
    through different handlers, and stale cache entries could ask a user to
    verify again even though their access window is still active.
    """
    status = await db.get_verified(userid)
    if not isinstance(status, dict):
        status = {"date": "1999-12-31", "time": "23:59:59"}
    temp.VERIFY[userid] = status
    return status

async def update_verify_status(userid, date_temp, time_temp):
    status = {"date": str(date_temp), "time": str(time_temp)}
    # Persist first so the access window survives restarts and is immediately
    # visible to both group and private-message delivery paths.
    await db.update_verification(userid, date_temp, time_temp)
    temp.VERIFY[userid] = status

